#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE DATABASE $AUTHFRAME_DB_NAME;
    CREATE DATABASE $SPICEDB_DB_NAME;
    CREATE DATABASE $ECMP_DB_NAME;
    CREATE DATABASE $KEYCLOAK_DB_NAME;
EOSQL

# Create DB users
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE USER $DB_USER WITH PASSWORD '$DB_PASSWORD';
EOSQL

# Grant privileges on the databases to the user and read-only user (RO only allow CONNECT)
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    GRANT ALL PRIVILEGES ON DATABASE $AUTHFRAME_DB_NAME TO $DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $SPICEDB_DB_NAME TO $DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $ECMP_DB_NAME TO $DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $KEYCLOAK_DB_NAME TO $DB_USER;
EOSQL

# Manage permissions for AUTHFRAME
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" -d "$AUTHFRAME_DB_NAME" <<-EOSQL
    GRANT CREATE ON SCHEMA public TO  $DB_USER;
EOSQL

# Manage permissions for SPICEDB
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" -d "$SPICEDB_DB_NAME" <<-EOSQL
    GRANT CREATE ON SCHEMA public TO  $DB_USER;
EOSQL

# Manage permissions for PAP
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" -d "$ECMP_DB_NAME" <<-EOSQL
    GRANT CREATE ON SCHEMA public TO  $DB_USER;
EOSQL

# Manage permissions for KEYCLOAK
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" -d "$KEYCLOAK_DB_NAME" <<-EOSQL
    GRANT CREATE ON SCHEMA public TO  $DB_USER;
EOSQL